import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const out = '.asset-build/performance-review/check';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
await page.goto('http://127.0.0.1:5184/birthday-card/performance-review.html');
await page.locator('[data-ready="true"]').waitFor({ timeout: 60000 });
for (const [label, name] of [['弹琴', 'piano'], ['起身', 'stand'], ['走近', 'approach'], ['牵手', 'hold'], ['侧步', 'step'], ['转身', 'turn'], ['收势', 'settle']]) {
  await page.getByRole('button', { name: label, exact: true }).click();
  await page.waitForTimeout(300);
  await page.locator('.duet-stage').screenshot({ path: `${out}/${name}.png` });
}
await page.getByRole('button', { name: '牵手', exact: true }).click();
await page.getByRole('button', { name: '手掌接触', exact: true }).click();
await page.waitForTimeout(300);
await page.locator('.duet-stage').screenshot({ path: `${out}/hands-close.png` });
await page.getByRole('button', { name: '弹琴', exact: true }).click();
await page.getByRole('button', { name: '琴键与坐姿', exact: true }).click();
await page.waitForTimeout(300);
await page.locator('.duet-stage').screenshot({ path: `${out}/piano-close.png` });
await page.getByRole('button', { name: '全身构图', exact: true }).click();
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/phone.png` });
await writeFile(`${out}/errors.json`, JSON.stringify(errors, null, 2));
console.log(JSON.stringify({ errors, output: out }));
await browser.close();
